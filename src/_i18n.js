// Resolve the current language lazily so this helper works even before
// _renderer.js assigns `window.settings` (the app UI is English-first, so an
// unset language means English).
window.t = key => {
    const lang = (window.settings && window.settings.language) || "en";
    const dict = window.I18N[lang] || window.I18N.en;
    return dict[key] ?? key;
};
